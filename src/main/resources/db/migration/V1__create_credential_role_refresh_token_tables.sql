CREATE TABLE CREDENTIAL_TBL(
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE ROLE_TBL(
    id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(20) NOT NULL UNIQUE
);

INSERT INTO ROLE_TBL(name)
VALUES ('ROLE_ADMIN'), ('ROLE_CUSTOMER');

CREATE TABLE CREDENTIAL_ROLE_TBL(
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    credential_id UUID NOT NULL,
    role_id INT NOT NULL,

    CONSTRAINT fk_credential_role_credential FOREIGN KEY (credential_id) REFERENCES CREDENTIAL_TBL(id),
    CONSTRAINT fk_credential_role_role FOREIGN KEY (role_id) REFERENCES ROLE_TBL(id)
);

CREATE TABLE REFRESH_TOKEN_TBL(
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    credential_id UUID NOT NULL,

    CONSTRAINT fk_refresh_token_credential FOREIGN KEY (credential_id) REFERENCES CREDENTIAL_TBL(id)
);